"""
gen_noise_results_md.py
=======================
Regenerate experiment_results/noise_models/RESULTS.md from the fresh CNN sweep
CSV (ler_noise_models.csv). Tables + key observations are derived from the data;
noise-model facts mirror run_ler_noise_models.py (CNN readout, not HERQULES).
"""
import csv
import numpy as np

CSV = "experiment_results/noise_models/ler_noise_models.csv"
OUT = "experiment_results/noise_models/RESULTS.md"

RO = [200, 400, 600, 800, 1000]
CODE_ORDER = ["surface", "bacon", "color", "hh", "steane", "gross"]
MODELS = [
    ("heron_cnn", "Model 1 - ibm_boston gates + CNN readout + decoherence"),
    ("readout_decoherence", "Model 2 - CNN readout + decoherence (gate errors = 0)"),
    ("decoherence_only", "Model 3 - decoherence only (readout flip = 0)"),
]
CNN_ACC = {200: (0.782, 0.864, 0.774, 0.770), 400: (0.907, 0.926, 0.901, 0.951),
           600: (0.953, 0.938, 0.937, 0.970), 800: (0.965, 0.941, 0.944, 0.970),
           1000: (0.970, 0.942, 0.947, 0.970)}

rows = list(csv.DictReader(open(CSV)))


def merr(ns):
    a = CNN_ACC[ns]
    return 1.0 - (a[0] * a[1] * a[2] * a[3]) ** 0.25


def ler(code, d, model, ns):
    for r in rows:
        if (r["code"] == code and int(r["distance"]) == d
                and r["noise_model"] == model and int(r["readout_ns"]) == ns):
            v = r["logical_error_rate"]
            return float(v) if v not in ("", "None") else None
    return None


def dec_of(code):
    for r in rows:
        if r["code"] == code:
            return r["decoder"]
    return "?"


def dists(code, model):
    return sorted({int(r["distance"]) for r in rows
                   if r["code"] == code and r["noise_model"] == model})


def fmt(x):
    return f"{x:.5f}" if x is not None else "-"


def model_table(model):
    out = ["| code | d | dec | 200 | 400 | 600 | 800 | 1000 |",
           "|---|---|---|---|---|---|---|---|"]
    for code in CODE_ORDER:
        for d in dists(code, model):
            cells = " | ".join(fmt(ler(code, d, model, ns)) for ns in RO)
            out.append(f"| {code} | {d} | {dec_of(code)} | {cells} |")
    return "\n".join(out)


# ---- data-derived observation helpers ----
def avg_abs_diff(m1, m2):
    diffs = []
    for code in CODE_ORDER:
        for d in dists(code, m1):
            for ns in RO:
                a, b = ler(code, d, m1, ns), ler(code, d, m2, ns)
                if a is not None and b is not None:
                    diffs.append(abs(a - b))
    return np.mean(diffs) if diffs else float("nan")


def optimum_ns(code, model, d):
    vals = [(ns, ler(code, d, model, ns)) for ns in RO if ler(code, d, model, ns) is not None]
    return min(vals, key=lambda t: t[1]) if vals else (None, None)


def over_threshold_d(code, model, thresh=0.45):
    """Smallest distance whose LER stays >= thresh across all readouts (saturated)."""
    for d in dists(code, model):
        vals = [ler(code, d, model, ns) for ns in RO if ler(code, d, model, ns) is not None]
        if vals and min(vals) >= thresh:
            return d
    return None


def bacon_max_decoh():
    vals = [ler("bacon", d, "decoherence_only", ns) for d in dists("bacon", "decoherence_only") for ns in RO]
    vals = [v for v in vals if v is not None]
    return max(vals) if vals else float("nan")


m1_m2 = avg_abs_diff("heron_cnn", "readout_decoherence")
opt_surface5 = optimum_ns("surface", "heron_cnn", 5)
opt_color5 = optimum_ns("color", "heron_cnn", 5)
ot_surface = over_threshold_d("surface", "decoherence_only")
ot_color = over_threshold_d("color", "decoherence_only")
ot_hh = over_threshold_d("hh", "decoherence_only")
gross_min = min(v for d in dists("gross", "heron_cnn") for ns in RO
                if (v := ler("gross", d, "heron_cnn", ns)) is not None)
bacon_mx = bacon_max_decoh()
me = {ns: merr(ns) for ns in RO}

md = f"""# LER vs noise model - six QEC codes, EXACT ibm_boston (Heron r3) + CNN readout

Generated by `run_ler_noise_models.py`; tables/observations regenerated from
`ler_noise_models.csv` by `gen_noise_results_md.py`.

## Noise model (verified)

Everything is **exactly ibm_boston**, EXCEPT the readout error/length which come from the **CNN MCM decoder**:

- Gate errors: SX = 1.637e-4, CZ = 1.191e-3 (ibm_boston dashboard medians).
- Coherence: T1 = 284.95 us (ibm_boston ref), T2 = 322.68 us (dashboard). idle_multiplier = 1.0.
- Gate latencies: SX = 32 ns, CZ = 68 ns; **reset = 0 (noiseless/instantaneous)** -- ibm_boston (evaluate_mcm_latency.py).
- Readout (the CNN exception): measure_error = 1 - geomean(Q1,Q3,Q4,Q5), Q2 excluded, swept over length.

| readout ns | 200 | 400 | 600 | 800 | 1000 |
|---|---|---|---|---|---|
| measure_error | {me[200]:.4f} | {me[400]:.4f} | {me[600]:.4f} | {me[800]:.4f} | {me[1000]:.4f} |

- Distances: surface/bacon/color/hh = 5,7,9,11,13; gross = 12 (fixed); steane = 9 (only d in {{3,9,27}}).
- Decoders: surface, hh -> MWPM (20k shots); bacon, color, steane, gross -> BP+OSD osd_0 (5k; gross 1k).

## {MODELS[0][1]}
LER, columns = readout 200/400/600/800/1000 ns:

{model_table("heron_cnn")}

## {MODELS[1][1]}
LER, columns = readout 200/400/600/800/1000 ns:

{model_table("readout_decoherence")}

## {MODELS[2][1]}
LER, columns = readout 200/400/600/800/1000 ns:

{model_table("decoherence_only")}

## Key observations
1. **Readout flip error falls monotonically with length** (CNN: {me[200]:.3f} -> {me[1000]:.3f}), so for the
   small/correctable distances LER drops steeply from 200 ns then flattens; e.g. surface d=5 (Model 1) bottoms at
   {opt_surface5[1]:.4f} @ {opt_surface5[0]} ns, color d=5 at {opt_color5[1]:.4f} @ {opt_color5[0]} ns. Beyond ~600 ns
   the residual decoherence (Model 3) offsets further flip-error gains, so the curve is flat-to-slightly-rising.
2. **Readout flip dominates over gate errors:** Model 1 ~ Model 2 -- zeroing SX/CZ moves LER by only
   {m1_m2:.4f} on average. Model 3 (no readout flip) is far lower.
3. **Decoherence-only (Model 3) threshold behaviour:** Bacon-Shor is solidly **sub-threshold** (max LER
   {bacon_mx:.5f} across all d incl. d=13). Surface/color/hh are sub-threshold only at low d and go **over
   threshold** by d={ot_surface}/{ot_color}/{ot_hh} respectively (LER rises toward ~0.5 with d).
4. **Gross saturates at LER ~ 1.0** in all models (min {gross_min:.5f}; 12 logical qubits, far over threshold).
5. **Models 1 & 2 are over threshold for d >= 9-11** across surface/color/hh even at the readout optimum
   (LER ~ 0.5), driven by the CNN readout flip + decoherence; only the low distances are correctable.
"""

with open(OUT, "w") as f:
    f.write(md)
print(f"wrote {OUT} ({len(md.splitlines())} lines)")
print(f"  m1~m2 avg|diff|={m1_m2:.4f}  surface5 opt={opt_surface5}  color5 opt={opt_color5}")
print(f"  decoh over-thresh d: surface={ot_surface} color={ot_color} hh={ot_hh}  bacon max={bacon_mx:.5f}  gross min={gross_min:.5f}")
